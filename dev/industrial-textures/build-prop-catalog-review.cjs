'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
global.IndustrialTextures = { isRemaster: () => true, enabled: () => true, ready: Promise.resolve() };
global.PropRemaster = { isProjection: () => true, enabled: () => false, revision:()=>0, ready: Promise.resolve() };
const P = require(path.join(root, 'frontend/app/propsprites.js'));
const manifestFile = 'frontend/assets/industrial/projection-correction/manifest.json';
const bytes = fs.readFileSync(path.join(root, manifestFile)), manifest = JSON.parse(bytes);
const structure = JSON.parse(fs.readFileSync(path.join(root, 'dev/industrial-textures/prop-structure-manifest.json')));
const faces = ['s', 'w', 'n', 'e'], views = [], skipped = [];
for (const spec of P.CATALOG) for (const r of P.facings(spec.id)) {
  // a row may WEAR another prop's finished art (catalog artId, e.g. the plugin terminal wears the dispatch pylon) — same
  // lookup the runtime makes (propsprites: PropRemaster.draw(c.artId || c.id, …))
  const artId = spec.artId || spec.id;
  const v = P.viewAt(spec.id, r), face = faces[r], candidates = manifest.props[artId]?.views || {};
  const artFace = candidates[face] ? face : (v.turned ? 's' : v.mirror ? (face === 'w' ? 'e' : 'w') : 's');
  const art = candidates[artFace], fp = P.footprintAt(spec.id, r);
  /* A PROP THE PROJECTION PACK DOES NOT CARRY is drawn PROCEDURALLY only (the SIGNS, 2026-10-21:
     their art is drawn live, with the Commander's own words on it, so there is no projected
     picture to correct). The review harness pages through the PACK — it has nothing to show for
     such a prop, so it is skipped, not faked and not fatal. */
  if (!art) {
    if (!manifest.props[artId]) { skipped.push(spec.id + ':' + face); break; }   // no projected art at all: skip the prop
    throw Error('No art for native view ' + spec.id + ':' + face);
  }
  const bounds = structure.props[artId]?.views?.[face]?.bounds || art.bounds;
  views.push({ key: spec.id + ':' + face, id: spec.id, face, r, label: spec.label,
    category: spec.cat, tier: spec.tier, footprint: fp, bounds,
    placement: spec.mount === 'wall' ? 'wall' : spec.mount === 'surface' || spec.stack ? 'surface' : spec.flat ? 'decal' : 'floor',
    requiredMount: spec.mount || null, optionalStack: !!spec.stack, flat: !!spec.flat,
    artFace, nativeMirror: !!v.mirror, nativeTurn: !!v.turned, image: art.image,
    surface: !!spec.surface, animated: !!spec.animated });
}
const data = { version: 1, catalogTypes: P.CATALOG.length, supportedViews: views.length,
  source: manifestFile, sourceSha256: crypto.createHash('sha256').update(bytes).digest('hex'),
  categories: Object.entries(P.CAT_LABEL).map(([id, label]) => ({ id, label })), views };
const text = '/* Generated by dev/industrial-textures/build-prop-catalog-review.cjs. */\n\'use strict\';\nconst PropCatalogData = ' + JSON.stringify(data, null, 2) + ';\nif (typeof module !== \'undefined\' && module.exports) module.exports = PropCatalogData;\n';
fs.writeFileSync(path.join(root, 'frontend/app/prop-catalog-data.js'), text);
console.log(JSON.stringify({ types: data.catalogTypes, directions: views.length, mirrors: views.filter(v => v.nativeMirror).length, decalTurns: views.filter(v => v.nativeTurn).length, skippedWithoutProjectedArt: skipped }));
