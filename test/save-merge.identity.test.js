'use strict';
const A = require('./_assert.js');
const { mergeHistory } = require('../sidecar/save-merge.js');
const { plan } = require('../sidecar/save-restore.js');
const { runTurnId, isTurnId } = require('../frontend/app/turnkinds.js');
const T = runTurnId('run-one'), T2 = runTurnId('run-two');
A.ok(isTurnId(T) && isTurnId(T2), 'fixture turn ids satisfy the shared grammar');
const U = { role: 'user', content: 'question', turnId: T };
const reply = { role: 'assistant', content: 'answer', turnId: T, sourceRunId: 'r' };
const other = { role: 'user', content: 'other question', turnId: T2 };
const bound = Object.assign({}, U, { rowId: 1, streamId: 's', content: 'station question' });
const merge = (B, W, S) => mergeHistory(B, W, S, 's', { overrode: [] });
A.eq(merge([U], [U, reply], [bound, other]), [bound, other, reply], 'two-window merge never mistakes assistant T for user T');
A.eq(merge([], [U], [bound]), [bound], 'unbound directive against its bound copy stays one user row');
A.eq(merge([U], [U, reply], [bound, reply]), [bound, reply], 'repeating the same save does not duplicate a reply');
const doc = history => ({ workstreams: [{ id: 's', createdAt: 1, lastActiveAt: 2, history }] });
const restored = plan(doc([bound]), doc([U, reply]));
A.eq(restored.doc.workstreams[0].history, [bound, reply], 'restoring an idless user+assistant extends the bound station directive with its assistant');
const collisionA = Object.assign({}, bound, { idFrom: 'collision', content: 'one' });
const collisionB = Object.assign({}, collisionA, { content: 'two' });
A.eq(merge([], [collisionA], [collisionB]).length, 2, 'collision metadata prevents save identity from erasing different station bytes');
A.report('save-merge.identity');
