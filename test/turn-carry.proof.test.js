'use strict';
const A = require('./_assert.js');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const { makeSegmentedTranscriptIo } = require('../sidecar/transcript-history.js');
const { makeTranscriptStore } = require('../sidecar/transcriptstore.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'turn-carry-proof-'));
const now = 10000000, requests = Array.from({ length: 8 }, (_, i) => ({ turnId: 'carry_absent_000' + i, turnAt: now - i * 1000 }));
const open = () => makeSegmentedTranscriptIo({ fs, path, root, segmentBytes: 4096, onWarning() {}, schedule() {} });
let io;
try {
  io = open();
  for (let i = 0; i < 24; i++) io.appendDurable({ streamId: 's', role: i % 2 ? 'assistant' : 'user', content: 'row ' + i, ts: now - 10000 + i });
  io.close(); io = open();
  const calls = [], original = io.history;
  io.history = (stream, options) => { if (options && options.vouch) calls.push(options); return original(stream, options); };
  let store = makeTranscriptStore({ io, ramPerStream: 3, clock: { now: () => now } });
  A.ok(store.count() < 24, 'fixture RAM does not contain the whole durable stream');
  let out = store.findTurns('s', requests);
  A.eq([...out.values()].map(r => r.state), Array(8).fill('absent'), 'all eight absent turns share a complete proof');
  A.eq(calls.length, 1, 'exactly one rung-four coverage IO call serves the batch');
  A.eq(calls[0].vouch.claims, requests.map(r => r.turnId), 'the read claims every requested turn, not only the first');
  A.eq(calls[0].since, now - 7000 - 600000, 'oldest requested clock defines shared coverage');
  const prior = calls.length;
  A.throws(() => store.findTurns('s', requests.concat(requests[0])), 'over-eight proof input is rejected before dedup');
  A.throws(() => store.findTurns('s', [{ turnId: requests[0].turnId }]), 'missing clock cannot prove absence');
  A.eq(calls.length, prior, 'invalid batches perform no coverage read');
  const row = store.appendStrict({ streamId: 's', role: 'user', agentId: 'a', content: 'now present', turnId: requests[0].turnId, directive: true });
  out = store.findTurns('s', requests);
  A.eq(out.get(requests[0].turnId).directive.rowId, row.rowId, 'new assembly reads current presence, not a retained absence token');
  A.eq([...out.values()].filter(r => r.state === 'absent').length, 7, 'other absent turns still share their own current proof');
  io.close();
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
  const active = path.join(root, 'segment-' + String(manifest.activeSegment).padStart(6, '0') + '.jsonl');
  fs.appendFileSync(active, '{"streamId":"s","turnId":"' + requests[7].turnId + '","content"\n');
  io = open(); let reads = 0;
  const history = io.history;
  io.history = (stream, options) => { if (options && options.vouch) reads++; return history(stream, options); };
  store = makeTranscriptStore({ io, ramPerStream: 3, clock: { now: () => now } });
  out = store.findTurns('s', requests.slice(1));
  A.eq([...out.values()].map(r => r.state), Array(7).fill('unknown'), 'damaged final claim prevents absence for the entire shared coverage');
  A.eq(reads, 1, 'failed coverage is not reread once per candidate');
  A.throws(() => io.history('s', { vouch: { claims: [] } }), 'empty claim batch is never unbounded authority');
  A.throws(() => io.history('s', { vouch: { claims: Array(9).fill('a') } }), 'IO owner enforces the same claim bound');
} finally { if (io) io.close(); fs.rmSync(root, { recursive: true, force: true }); }
A.report('turn-carry.proof');
